async function seed() {
  console.log(`Seeding ${resources.length} resources to Supabase...`);
  
  let inserted = 0;
  let failed = 0;
  
  for (const resource of resources) {
    try {
      // Check if resource with same name exists
      const existing = await sql`SELECT id FROM resources WHERE name = ${resource.name} LIMIT 1`;
      
      if (existing.length > 0) {
        // Update existing
        await sql`
          UPDATE resources SET
            description = ${resource.description || null},
            category = ${resource.category},
            contact = ${JSON.stringify(resource.contact || {})},
            service_area = ${resource.serviceArea || null},
            service_area_type = ${resource.serviceAreaType || 'local'},
            service_zip_codes = ${resource.serviceZipCodes || null},
            service_cities = ${resource.serviceCities || null},
            service_counties = ${resource.serviceCounties || null},
            service_states = ${resource.serviceStates || null},
            is_nationwide = ${resource.isNationwide || false},
            eligibility = ${resource.eligibility || null},
            is_verified = ${resource.isVerified || false},
            updated_at = NOW()
          WHERE name = ${resource.name}
        `;
      } else {
        // Idempotent insert: if a concurrent seeder already created this
        // resource (case-insensitive name uniqueness enforced by
        // resources_name_lower_key in db-init.ts) we silently skip.
        await sql`
          INSERT INTO resources (
            name, description, category, contact, 
            service_area, service_area_type, service_zip_codes, 
            service_cities, service_counties, service_states, is_nationwide,
            eligibility, is_verified, connection_type, has_sainte_access
          ) VALUES (
            ${resource.name},
            ${resource.description || null},
            ${resource.category},
            ${JSON.stringify(resource.contact || {})},
            ${resource.serviceArea || null},
            ${resource.serviceAreaType || 'local'},
            ${resource.serviceZipCodes || null},
            ${resource.serviceCities || null},
            ${resource.serviceCounties || null},
            ${resource.serviceStates || null},
            ${resource.isNationwide || false},
            ${resource.eligibility || null},
            ${resource.isVerified || false},
            ${resource.connectionType || 'external'},
            ${resource.hasSainteAccess || false}
          )
          ON CONFLICT ((LOWER(name))) DO NOTHING
        `;
      }
      inserted++;
    } catch (err: any) {
      console.error(`Failed to insert ${resource.name}:`, err?.message);
      failed++;
    }
  }
  
  console.log(`\nSeeding complete:`);
  console.log(`  Inserted/Updated: ${inserted}`);
  console.log(`  Failed: ${failed}`);
  
  // Show category breakdown
  const stats = await sql`
    SELECT category, COUNT(*) as count 
    FROM resources 
    GROUP BY category 
    ORDER BY count DESC
  `;
  
  console.log(`\nResources by category:`);
  for (const row of stats) {
    console.log(`  ${row.category}: ${row.count}`);
  }
  
  await sql.end();
}

seed().catch(e => {
  console.error("Seeding failed:", e);
  process.exit(1);
});
